"""Render docs/dataset_card.md from a profiling report.

[DECISION] The dataset card is generated from reports/phase01/profile_summary.json
(and, once it exists, the dev-scope selection summary) rather than hand-typed,
so every number in it traces back to a specific profiling run instead of being
retyped from memory. Sections that don't come from the data (source, license
status, JD-dimension mapping) are written directly in this module, clearly
separated from the generated numbers.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


def _fmt(value: Any) -> str:
    if isinstance(value, float):
        return f"{value:,.4f}"
    if isinstance(value, int):
        return f"{value:,}"
    return str(value)


def _pct(share: float) -> str:
    return f"{share * 100:.2f}%"


def render_dataset_card(
    profile: dict[str, Any],
    dev_scope_summary: dict[str, Any] | None,
    dataset_display_name: str,
    kaggle_competition_slug: str,
) -> str:
    generated_at = datetime.now(timezone.utc).isoformat()
    grain = profile.get("sales_grain") or {}
    dates = profile.get("sales_date_coverage") or {}
    validity = profile.get("sales_value_validity") or {}
    refint = profile.get("referential_integrity") or {}
    dims = profile.get("dimension_coverage") or {}
    row_counts = profile.get("row_counts") or {}

    lines: list[str] = []
    lines.append(f"# Dataset Card — {dataset_display_name}")
    lines.append("")
    lines.append(
        "> Generated by `demandflow.reporting.generate_dataset_card` from "
        f"`reports/phase01/profile_summary.json`, profiled at "
        f"`{profile.get('profiled_at_utc', 'unknown')}`. This file itself was "
        f"rendered at `{generated_at}`. Do not hand-edit the numbers below — "
        "re-run the Phase 01 profiling pipeline and regenerate instead."
    )
    lines.append("")
    lines.append("## Source")
    lines.append("")
    lines.append(
        f"- **[DECISION]** Primary dataset selected in Phase 00 "
        f"(see `docs/decisions/0001-phase00-decisions-and-scope.md`): "
        f"the **{dataset_display_name}** Kaggle competition "
        f"(`{kaggle_competition_slug}`)."
    )
    lines.append(
        "- **[VERIFY]** License / redistribution terms: governed by the Kaggle "
        "competition rules in effect when the data was downloaded. Not "
        "independently re-verified by this generator — see the acquisition "
        "manifest's `downloaded_at_utc` and check the competition's rules page "
        "for the terms as they stood on that date. This is also why raw data "
        "is never committed to this repository (see `.gitignore`)."
    )
    lines.append(
        "- **Scope note:** this is an anonymized, industry-inspired portfolio "
        "project. This dataset is not, and is not claimed to be, data from the "
        "target company described (anonymized) in `CLAUDE.md` §1."
    )
    lines.append("")

    lines.append("## Tables and row counts (as profiled)")
    lines.append("")
    lines.append("| Table | Row count |")
    lines.append("|---|---|")
    for table in sorted(row_counts):
        lines.append(f"| `{table}` | {_fmt(row_counts[table])} |")
    lines.append("")

    lines.append("## Grain and key uniqueness")
    lines.append("")
    if grain:
        lines.append(
            f"- Declared grain: `{', '.join(grain.get('key_columns', []))}`."
        )
        lines.append(f"- Total rows: {_fmt(grain.get('total_rows', 0))}")
        lines.append(f"- Distinct key combinations: {_fmt(grain.get('distinct_key_rows', 0))}")
        lines.append(
            f"- **Duplicate rows on this key: {_fmt(grain.get('duplicate_rows', 0))}** "
            f"({'grain is unique' if grain.get('is_unique') else 'grain is NOT unique — see Phase 02 for handling'})."
        )
    else:
        lines.append("_Not available — the sales table was not found in the profiled source._")
    lines.append("")

    lines.append("## Time coverage")
    lines.append("")
    if dates:
        lines.append(f"- Date range: `{dates.get('min_date')}` to `{dates.get('max_date')}`")
        lines.append(f"- Distinct calendar dates with at least one row: {_fmt(dates.get('distinct_dates', 0))}")
        lines.append(f"- Expected calendar days in range: {_fmt(dates.get('expected_calendar_days', 0))}")
        lines.append(f"- **Missing calendar dates (zero rows on that date, any store/item): {_fmt(dates.get('missing_dates_count', 0))}**")
        sample = dates.get("missing_dates_sample") or []
        if sample:
            lines.append(f"  - Sample of missing dates: {', '.join(sample)}")
    else:
        lines.append("_Not available._")
    lines.append("")

    lines.append("## Value validity")
    lines.append("")
    if validity:
        lines.append(f"- Negative `unit_sales` rows (returns, per public documentation [VERIFY]): "
                      f"{_fmt(validity.get('negative_unit_sales_count', 0))} "
                      f"({_pct(validity.get('negative_unit_sales_share', 0.0))} of rows)")
        lines.append(f"- Fractional `unit_sales` rows (items sold by weight): "
                      f"{_fmt(validity.get('fractional_unit_sales_count', 0))}")
        lines.append(f"- `onpromotion` NULL: {_fmt(validity.get('onpromotion_null_count', 0))} "
                      f"({_pct(validity.get('onpromotion_null_share', 0.0))} of rows) — "
                      "[VERIFY] against the ~16% figure reported in public write-ups reviewed in Phase 00")
        lines.append(f"- `onpromotion` True / False: "
                      f"{_fmt(validity.get('onpromotion_true_count', 0))} / "
                      f"{_fmt(validity.get('onpromotion_false_count', 0))}")
    else:
        lines.append("_Not available._")
    lines.append("")

    lines.append("## Referential integrity")
    lines.append("")
    if refint:
        lines.append(f"- Sales rows referencing an unknown `store_nbr`: {_fmt(refint.get('sales_rows_with_unknown_store', 0))}")
        lines.append(f"- Sales rows referencing an unknown `item_nbr`: {_fmt(refint.get('sales_rows_with_unknown_item', 0))}")
    else:
        lines.append("_Not available._")
    lines.append("")

    lines.append("## Dimension coverage against the target-role JD dimensions")
    lines.append("")
    lines.append(
        "[JD] The target-role profile (`CLAUDE.md` §1) asks for analysis across "
        "SKUs, hubs, categories, campaigns, pricing, and seasonal events. "
        "Coverage found in this dataset, as profiled:"
    )
    lines.append("")
    lines.append("| JD dimension | Found in this dataset | Detail |")
    lines.append("|---|---|---|")
    stores_dim = dims.get("stores", {})
    items_dim = dims.get("items", {})
    holidays_dim = dims.get("holidays_events", {})
    lines.append(
        f"| SKUs | Yes | {_fmt(items_dim.get('count', 0))} items across "
        f"{_fmt(items_dim.get('distinct_families', 0))} families, "
        f"{_fmt(items_dim.get('distinct_classes', 0))} classes "
        f"({_fmt(items_dim.get('perishable_count', 0))} perishable / "
        f"{_fmt(items_dim.get('non_perishable_count', 0))} non-perishable) |"
    )
    lines.append(
        f"| Hubs | Partial (stores used as a proxy — see ADR 0001 A1) | "
        f"{_fmt(stores_dim.get('count', 0))} stores, "
        f"{_fmt(stores_dim.get('distinct_cities', 0))} cities, "
        f"{_fmt(stores_dim.get('distinct_states', 0))} states, "
        f"{_fmt(stores_dim.get('distinct_types', 0))} store types, "
        f"{_fmt(stores_dim.get('distinct_clusters', 0))} clusters |"
    )
    lines.append(
        f"| Categories | Yes | {_fmt(items_dim.get('distinct_families', 0))} families "
        f"/ {_fmt(items_dim.get('distinct_classes', 0))} classes |"
    )
    lines.append(
        f"| Campaigns | Partial | `onpromotion` flag per item x store x day "
        f"({_pct(validity.get('onpromotion_null_share', 0.0)) if validity else 'n/a'} NULL) "
        "— a flag, not a named campaign |"
    )
    lines.append("| Pricing | **No** | Not present in this dataset — documented limitation (ADR 0001 D2) |")
    lines.append(
        f"| Seasonal events | Yes | holidays_events: "
        f"{', '.join(f'{k}={v}' for k, v in (holidays_dim.get('by_type') or {}).items())} "
        f"by type; {', '.join(f'{k}={v}' for k, v in (holidays_dim.get('by_locale') or {}).items())} by locale |"
    )
    lines.append("")

    lines.append("## Controlled development scope")
    lines.append("")
    if dev_scope_summary:
        lines.append(
            f"- Items selected: {_fmt(dev_scope_summary.get('selected_items', 0))} of "
            f"{_fmt(dev_scope_summary.get('total_items', 0))} "
            f"({_pct(dev_scope_summary.get('selected_item_fraction', 0.0))})"
        )
        lines.append(
            f"- Share of total historical unit sales covered by the selected items: "
            f"{_pct(dev_scope_summary.get('selected_share_of_total_unit_sales', 0.0))}"
        )
        lines.append(f"- Stratum cells: {_fmt(dev_scope_summary.get('stratum_cells', 0))}")
        lines.append(
            f"- Families represented in the selection: "
            f"{', '.join(dev_scope_summary.get('families_represented_in_selection', []))}"
        )
        lines.append(
            "- Methodology, validation, and reproducibility details: see "
            "`docs/decisions/0001-phase00-decisions-and-scope.md` §2 and "
            "`configs/dev_scope_items.csv`."
        )
    else:
        lines.append("_Not yet run — see `demandflow.scope.select_dev_scope`._")
    lines.append("")

    lines.append("## Known limitations")
    lines.append("")
    lines.append("- **No item-level pricing.** Accepted as a documented dataset limitation (ADR 0001 D2), not addressed by a second dataset for now.")
    lines.append("- **No stockout or availability signal.** A missing sales row cannot be distinguished from a true zero-demand day without further assumptions (see Phase 00 plan, risk K3/K4).")
    lines.append("- **\"Hub\" is simulated by \"store\".** These are supermarkets, not quick-commerce dark stores (ADR 0001 A1).")
    lines.append("- **Regional/seasonal calendar is Ecuadorian**, not the target company's real operating region.")
    lines.append("")

    return "\n".join(lines)


def generate_and_write(
    profile_path: Path,
    dev_scope_summary_path: Path | None,
    out_path: Path,
    dataset_display_name: str,
    kaggle_competition_slug: str,
) -> Path:
    profile = json.loads(profile_path.read_text(encoding="utf-8"))
    dev_scope_summary = (
        json.loads(dev_scope_summary_path.read_text(encoding="utf-8"))
        if dev_scope_summary_path and dev_scope_summary_path.exists()
        else None
    )
    content = render_dataset_card(
        profile, dev_scope_summary, dataset_display_name, kaggle_competition_slug
    )
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(content, encoding="utf-8")
    return out_path


def _main() -> None:
    from demandflow.config import load_config

    cfg = load_config()
    profile_path = cfg.paths.reports_dir / "phase01" / "profile_summary.json"
    dev_scope_summary_path = cfg.paths.reports_dir / "phase01" / "dev_scope_summary.json"
    if not profile_path.exists():
        raise FileNotFoundError(
            f"Expected {profile_path} to exist. Run demandflow.profiling.profile_favorita first."
        )
    out_path = Path("docs") / "dataset_card.md"
    generate_and_write(
        profile_path=profile_path,
        dev_scope_summary_path=dev_scope_summary_path,
        out_path=out_path,
        dataset_display_name=cfg.dataset.display_name,
        kaggle_competition_slug=cfg.dataset.kaggle_competition_slug,
    )
    print(f"Wrote {out_path}")


if __name__ == "__main__":
    _main()
